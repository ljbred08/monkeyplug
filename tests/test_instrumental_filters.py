# -*- coding: utf-8 -*-

"""Tests for instrumental splice filter construction.

Traditional mode used to `asplit` input 0 and use one of those copies as the
"instrumental" stream, which spliced the original audio back into itself and
left the profanity audible. The instrumental is the second ffmpeg input ([1:a]).
"""

from monkeyplug.monkeyplug import Plugger


class MockPlugger:
    """Minimal mock Plugger for testing filter construction without audio files"""

    def __init__(self, segments, duration=200.0, autoGenerateMode=False, segMapping=None):
        self.instrumentalSegments = segments
        self.inputFileSpec = "fake.mp3"
        self.debug = False
        self.autoGenerateMode = autoGenerateMode
        self.segMapping = segMapping or []
        self._duration = duration

        self._get_file_duration = lambda path: self._duration
        self._build_instrumental_filters = Plugger._build_instrumental_filters.__get__(self)

    def filters(self):
        args = self._build_instrumental_filters()
        assert args[0] == "-filter_complex"
        return args[1]


class TestTraditionalInstrumentalFilters:
    """Traditional mode: user supplies an instrumental file as the second input"""

    def test_profanity_ranges_come_from_second_input(self):
        filters = MockPlugger([(10.0, 12.0)], duration=60.0).filters()

        # the profanity range is taken from the instrumental file, not the original
        assert "[1:a]atrim=10.00:12.00,asetpts=PTS-STARTPTS[seg1]" in filters
        # the original audio before it is untouched
        assert "[0:a]atrim=0.00:10.00,asetpts=PTS-STARTPTS[seg0]" in filters
        # and the tail after it is the original too
        assert "[0:a]atrim=12.00,asetpts=PTS-STARTPTS[seg2]" in filters
        # nothing is asplit from the original, which would defeat the whole splice
        assert "asplit" not in filters
        assert "[orig]" not in filters
        assert "[inst]" not in filters

    def test_multiple_segments_are_ordered_and_concatenated(self):
        filters = MockPlugger([(5.0, 6.0), (20.0, 21.5)], duration=30.0).filters()

        assert "[0:a]atrim=0.00:5.00,asetpts=PTS-STARTPTS[seg0]" in filters
        assert "[1:a]atrim=5.00:6.00,asetpts=PTS-STARTPTS[seg1]" in filters
        assert "[0:a]atrim=6.00:20.00,asetpts=PTS-STARTPTS[seg2]" in filters
        assert "[1:a]atrim=20.00:21.50,asetpts=PTS-STARTPTS[seg3]" in filters
        assert "[0:a]atrim=21.50,asetpts=PTS-STARTPTS[seg4]" in filters
        assert "[seg0][seg1][seg2][seg3][seg4]concat=n=5:v=0:a=1[outa]" in filters

    def test_no_empty_tail_segment_when_profanity_ends_the_file(self):
        filters = MockPlugger([(10.0, 12.0)], duration=12.0).filters()

        assert "concat=n=2" in filters
        assert "[0:a]atrim=12.00," not in filters

    def test_tail_kept_when_duration_is_unknown(self):
        filters = MockPlugger([(10.0, 12.0)], duration=0.0).filters()

        assert "[0:a]atrim=12.00,asetpts=PTS-STARTPTS[seg2]" in filters
        assert "concat=n=3" in filters


class TestAutoGeneratedInstrumentalFilters:
    """Auto-separation mode keeps using the generated combined file ([1:a])"""

    def test_uses_second_input(self):
        seg_mapping = [(10.0, 12.0, 0.0, 4.0, 9.0, 13.0)]
        filters = MockPlugger(
            [(10.0, 12.0)], duration=60.0, autoGenerateMode=True, segMapping=seg_mapping
        ).filters()

        assert "[1:a]atrim=1.00:3.00,asetpts=PTS-STARTPTS[seg1]" in filters
        assert "asplit" not in filters
