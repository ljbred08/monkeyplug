# End to end: run the filter graph through a real ffmpeg
def _write_wav(path, samples, rate=44100):
    pcm = (np.clip(samples, -1.0, 1.0) * 32767).astype("<i2")
    with wave.open(str(path), "wb") as handle:
        handle.setnchannels(1)
        handle.setsampwidth(2)
        handle.setframerate(rate)
        handle.writeframes(pcm.tobytes())


def _read_wav(path):
    with wave.open(str(path), "rb") as handle:
        rate = handle.getframerate()
        channels = handle.getnchannels()
        frames = handle.readframes(handle.getnframes())
    samples = np.frombuffer(frames, dtype="<i2").astype(np.float64) / 32768.0
    if channels > 1:
        samples = samples.reshape(-1, channels).mean(axis=1)
    return samples, rate


def _slice(samples, rate, start, end):
    return samples[int(start * rate):int(end * rate)]


def _rms(samples):
    return float(np.sqrt(np.mean(np.square(samples)))) if len(samples) else 0.0


def _tone_amplitude(samples, rate, frequency):
    window = samples * np.hanning(len(samples))
    spectrum = np.abs(np.fft.rfft(window)) * 2.0 / max(1, np.sum(np.hanning(len(samples))))
    freqs = np.fft.rfftfreq(len(samples), 1.0 / rate)
    return float(spectrum[int(np.argmin(np.abs(freqs - frequency)))])


def _render(tmp_path, filter_complex, inst_samples, vox_samples, duration=6.0):
    rate = 44100
    t = np.arange(int(duration * rate)) / rate
    _write_wav(tmp_path / "original.wav", 0.5 * np.sin(2 * np.pi * 440 * t))
    _write_wav(tmp_path / "instrumental.wav", inst_samples)
    _write_wav(tmp_path / "vocals.wav", vox_samples)

    output = tmp_path / "out.wav"
    cmd = [
        FFMPEG, "-nostdin", "-hide_banner", "-loglevel", "error", "-y",
        "-i", str(tmp_path / "original.wav"),
        "-i", str(tmp_path / "instrumental.wav"),
        "-i", str(tmp_path / "vocals.wav"),
        "-filter_complex", filter_complex,
        "-map", "[outa]",
        "-acodec", "pcm_s16le", "-ar", str(rate), "-ac", "1",
        str(output),
    ]
    result = subprocess.run(cmd, capture_output=True, text=True)
    assert result.returncode == 0, result.stderr
    return _read_wav(output)


class TestReverseModeAudio:
    """The rendered audio really contains the reversed vocal over the profanity"""

    DURATION = 6.0
    RATE = 44100

    def _filters(self, tmp_path):
        return MockPlugger(
            [(2.0, 3.0)], duration=self.DURATION, autoGenerateMode=True,
            segMapping=[(2.0, 3.0, 0.0, 4.0, 1.0, 4.0)],
            reverseMode=True, vocalsFileSpec=str(tmp_path / "vocals.wav"),
        ).filters()

    @requires_ffmpeg
    def test_instrumental_and_vocal_both_replace_the_original(self, tmp_path):
        n = int(self.DURATION * self.RATE)
        t = np.arange(n) / self.RATE
        # instrumental 880 Hz + vocal 1000 Hz, the original 440 Hz must be gone
        inst = 0.5 * np.sin(2 * np.pi * 880 * t)
        vox = 0.5 * np.sin(2 * np.pi * 1000 * t)

        samples, rate = _render(tmp_path, self._filters(tmp_path), inst, vox)

        censored = _slice(samples, rate, 2.05, 2.95)
        untouched = _slice(samples, rate, 0.45, 1.35)

        assert _tone_amplitude(censored, rate, 880) > 0.3, "instrumental missing from window"
        assert _tone_amplitude(censored, rate, 1000) > 0.3, "vocal missing from window"
        assert _tone_amplitude(censored, rate, 440) < 0.1, "original audio survived the splice"
        assert _tone_amplitude(untouched, rate, 440) > 0.3, "uncensored audio was altered"
        assert _tone_amplitude(untouched, rate, 1000) < 0.1

    @requires_ffmpeg
    def test_vocal_is_actually_reversed(self, tmp_path):
        n = int(self.DURATION * self.RATE)
        t = np.arange(n) / self.RATE
        # silent instrumental, so the window is the vocal alone
        inst = np.zeros(n)
        # vocal grows from silence: reversed, it must fade *out* inside the window
        forward_vox = 0.8 * np.sin(2 * np.pi * 1000 * t) * np.clip(t / self.DURATION, 0.0, 1.0)

        samples, rate = _render(tmp_path, self._filters(tmp_path), inst, forward_vox)

        early = _rms(_slice(samples, rate, 2.05, 2.45))
        late = _rms(_slice(samples, rate, 2.55, 2.95))
        assert early > 0.01, "censored window is silent"
        assert early > 1.2 * late, (
            f"vocal not reversed: early RMS {early:.4f} vs late RMS {late:.4f}"
        )

        # sanity: the source vocal grows the other way round
        source_early = _rms(_slice(forward_vox, rate, 1.05, 1.45))
        source_late = _rms(_slice(forward_vox, rate, 1.55, 1.95))
        assert source_early < source_late

    @requires_ffmpeg
    def test_vocal_edges_are_ramped_not_stepped(self, tmp_path):
        n = int(self.DURATION * self.RATE)
        # silent instrumental, flat vocal: spliced in raw, the window steps
        # straight up to 0.5 from whatever the 440 Hz track happened to hold
        inst = np.zeros(n)
        vox = np.full(n, 0.5)

        samples, rate = _render(tmp_path, self._filters(tmp_path), inst, vox)

        # steepest single-sample jump around both window edges
        edges = np.concatenate([
            _slice(samples, rate, 1.99, 2.02),
            _slice(samples, rate, 2.98, 3.01),
        ])
        steepest = float(np.max(np.abs(np.diff(edges))))

        # the 440 Hz track's own slope is ~0.031 per sample at 44.1 kHz; a hard
        # splice adds a step of up to the vocal's full 0.5
        assert steepest < 0.06, f"window edge still steps by {steepest:.3f}"


class _StubSeparator:
    """Stands in for SourceSeparator: returns prepared stems instead of running Spleeter"""

    def __init__(self, instrumental_samples, vocals_samples, duration=3.0):
        self.instrumental = instrumental_samples
        self.vocals = vocals_samples
        self.duration = duration

    def separate_audio_file(self, input_file, output_dir):
        instrumental_path = os.path.join(output_dir, "combined_profanity_instrumental.wav")
        vocals_path = os.path.join(output_dir, "combined_profanity_vocals.wav")
        _write_wav(instrumental_path, self.instrumental)
        _write_wav(vocals_path, self.vocals)
        return instrumental_path, vocals_path


class _SeparationPlugger:
    """Just enough of GroqPlugger to run the extraction/separate/splice path"""

    def __init__(self, input_file, cache_dir, separator, duration):
        self.inputFileSpec = input_file
        self.separationCacheDir = cache_dir
        self.separator = separator
        self.instrumentalSegments = [(2.0, 3.0)]
        self.segMapping = []
        self.separationPadding = 1.0
        self.debug = False
        self.reverseMode = True
        self.vocalsFileSpec = ""
        self.autoGenerateMode = True
        self._duration = duration
        self._get_file_duration = lambda path: self._duration
        self._build_instrumental_filters = Plugger._build_instrumental_filters.__get__(self)
        self._extract_combined_segments = GroqPlugger._extract_combined_segments.__get__(self)
        self._create_combined_profanity_file = GroqPlugger._create_combined_profanity_file.__get__(self)


class TestSeparationToSplice:
    """The separated vocal stem survives into the splice and ends up in the audio"""

    RATE = 44100
    DURATION = 6.0
    COMBINED_DURATION = 3.0  # 1.0s padding around a 2.0-3.0s profanity range

    def _plugger(self, tmp_path):
        t = np.arange(int(self.COMBINED_DURATION * self.RATE)) / self.RATE
        separator = _StubSeparator(
            # silent instrumental isolates the reversed vocal in the window
            np.zeros_like(t),
            # vocal grows over the combined file, so a reversed copy must fade out
            0.8 * np.sin(2 * np.pi * 1000 * t) * np.clip(t / self.COMBINED_DURATION, 0.0, 1.0),
        )
        original = tmp_path / "original.wav"
        sample_t = np.arange(int(self.DURATION * self.RATE)) / self.RATE
        _write_wav(original, 0.5 * np.sin(2 * np.pi * 440 * sample_t))
        return _SeparationPlugger(str(original), str(tmp_path), separator, self.DURATION)

    @requires_ffmpeg
    def test_vocal_stem_is_kept_and_reversed(self, tmp_path):
        plugger = self._plugger(tmp_path)

        instrumental = plugger._create_combined_profanity_file()

        assert instrumental and os.path.isfile(instrumental)
        # the separated vocal stem is remembered for reverse mode
        assert plugger.vocalsFileSpec and os.path.isfile(plugger.vocalsFileSpec)
        assert plugger.vocalsFileSpec.endswith("_vocals.wav")
        # one merged profanity window, translated into the combined file
        assert plugger.segMapping == [(2.0, 3.0, 0.0, 3.0, 1.0, 4.0)]

        filters = plugger._build_instrumental_filters()[1]
        output = tmp_path / "out.wav"
        cmd = [
            FFMPEG, "-nostdin", "-hide_banner", "-loglevel", "error", "-y",
            "-i", plugger.inputFileSpec,
            "-i", instrumental,
            "-i", plugger.vocalsFileSpec,
            "-filter_complex", filters,
            "-map", "[outa]",
            "-acodec", "pcm_s16le", "-ar", str(self.RATE), "-ac", "1",
            str(output),
        ]
        result = subprocess.run(cmd, capture_output=True, text=True)
        assert result.returncode == 0, result.stderr

        samples, rate = _read_wav(output)
        early = _rms(_slice(samples, rate, 2.05, 2.45))
        late = _rms(_slice(samples, rate, 2.55, 2.95))
        assert early > 0.01, "censored window is silent"
        assert early > 1.2 * late, "vocal in the window is not reversed"
        # the song outside the window is untouched
        assert _tone_amplitude(_slice(samples, rate, 0.45, 1.35), rate, 440) > 0.3
