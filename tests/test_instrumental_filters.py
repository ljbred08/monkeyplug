"""Tests for instrumental splice filter construction.

Traditional mode used to `asplit` input 0 and use one of those copies as the
"instrumental" stream, which spliced the original audio back into itself and
left the profanity audible. The instrumental is the second ffmpeg input ([1:a]).

Reverse mode (AI generation only) drops the instrumental *and* the reversed
vocal stem into each censored window, so those tests check both the filter
graph and the audio it actually produces.
"""

import os
import shutil
import subprocess
import wave

import numpy as np
import pytest

from monkeyplug.monkeyplug import GroqPlugger, Plugger


FFMPEG = shutil.which("ffmpeg")
requires_ffmpeg = pytest.mark.skipif(FFMPEG is None, reason="ffmpeg not available")


class MockPlugger:
    """Minimal mock Plugger for testing filter construction without audio files"""

    def __init__(self, segments, duration=200.0, autoGenerateMode=False, segMapping=None,
                 reverseMode=False, vocalsFileSpec=""):
        self.instrumentalSegments = segments
        self.inputFileSpec = "fake.mp3"
        self.debug = False
        self.autoGenerateMode = autoGenerateMode
        self.segMapping = segMapping or []
        self.reverseMode = reverseMode
        self.vocalsFileSpec = vocalsFileSpec
        self._duration = duration

        self._get_file_duration = lambda path: self._duration
        self._build_instrumental_filters = Plugger._build_instrumental_filters.__get__(self)

    def filters(self):
        args = self._build_instrumental_filters()
        assert args[0] == "-filter_complex"
        return args[1]


class TestTraditionalInstrumentalFilters:
    """Traditional mode: user supplies an instrumental file as the second input"""

    def test_profanity_ranges_come_from_second_input(self):
        filters = MockPlugger([(10.0, 12.0)], duration=60.0).filters()

        # the profanity range is taken from the instrumental file, not the original
        assert "[1:a]atrim=10.00:12.00,asetpts=PTS-STARTPTS[seg1]" in filters
        # the original audio before it is untouched
        assert "[0:a]atrim=0.00:10.00,asetpts=PTS-STARTPTS[seg0]" in filters
        # and the tail after it is the original too
        assert "[0:a]atrim=12.00,asetpts=PTS-STARTPTS[seg2]" in filters
        # nothing is asplit from the original, which would defeat the whole splice
        assert "asplit" not in filters
        assert "[orig]" not in filters
        assert "[inst]" not in filters

    def test_multiple_segments_are_ordered_and_concatenated(self):
        filters = MockPlugger([(5.0, 6.0), (20.0, 21.5)], duration=30.0).filters()

        assert "[0:a]atrim=0.00:5.00,asetpts=PTS-STARTPTS[seg0]" in filters
        assert "[1:a]atrim=5.00:6.00,asetpts=PTS-STARTPTS[seg1]" in filters
        assert "[0:a]atrim=6.00:20.00,asetpts=PTS-STARTPTS[seg2]" in filters
        assert "[1:a]atrim=20.00:21.50,asetpts=PTS-STARTPTS[seg3]" in filters
        assert "[0:a]atrim=21.50,asetpts=PTS-STARTPTS[seg4]" in filters
        assert "[seg0][seg1][seg2][seg3][seg4]concat=n=5:v=0:a=1[outa]" in filters

    def test_no_empty_tail_segment_when_profanity_ends_the_file(self):
        filters = MockPlugger([(10.0, 12.0)], duration=12.0).filters()

        assert "concat=n=2" in filters
        assert "[0:a]atrim=12.00," not in filters

    def test_tail_kept_when_duration_is_unknown(self):
        filters = MockPlugger([(10.0, 12.0)], duration=0.0).filters()

        assert "[0:a]atrim=12.00,asetpts=PTS-STARTPTS[seg2]" in filters
        assert "concat=n=3" in filters


class TestAutoGeneratedInstrumentalFilters:
    """Auto-separation mode keeps using the generated combined file ([1:a])"""

    def test_uses_second_input(self):
        seg_mapping = [(10.0, 12.0, 0.0, 4.0, 9.0, 13.0)]
        filters = MockPlugger(
            [(10.0, 12.0)], duration=60.0, autoGenerateMode=True, segMapping=seg_mapping
        ).filters()

        assert "[1:a]atrim=1.00:3.00,asetpts=PTS-STARTPTS[seg1]" in filters
        assert "asplit" not in filters


class TestReverseModeFilters:
    """Reverse mode: instrumental plus reversed vocal stem inside each censored window"""

    SEG_MAPPING = [(10.0, 12.0, 0.0, 4.0, 9.0, 13.0)]

    def reverse_filters(self, vocals="/tmp/combined_vocals.wav"):
        return MockPlugger(
            [(10.0, 12.0)], duration=60.0, autoGenerateMode=True,
            segMapping=self.SEG_MAPPING, reverseMode=True, vocalsFileSpec=vocals,
        ).filters()

    def test_vocal_stem_is_reversed_and_mixed_with_the_instrumental(self):
        filters = self.reverse_filters()

        # instrumental portion of the profanity window
        assert "[1:a]atrim=1.00:3.00,asetpts=PTS-STARTPTS[inst1]" in filters
        # same window of the vocal stem, reversed, and ramped at both edges
        assert (
            "[2:a]atrim=1.00:3.00,asetpts=PTS-STARTPTS,areverse,"
            "afade=t=in:st=0:d=0.010,afade=t=out:st=1.990:d=0.010[vox1]"
        ) in filters
        # both dropped back in together, unnormalised so the stems keep their levels
        assert "[inst1][vox1]amix=inputs=2:normalize=0[seg1]" in filters
        # the mixed segment still feeds the concat, so the timeline is unchanged
        assert "concat=n=3" in filters
        assert "[seg0][seg1][seg2]concat" in filters

    def test_vocal_envelope_does_not_change_the_timeline(self):
        # afade shapes the vocal in place; it must not consume the window the way
        # acrossfade would, or every swear word would shorten the track slightly
        filters = self.reverse_filters()

        assert "acrossfade" not in filters
        # the window is still a full two seconds, 1.00 -> 3.00
        assert "[1:a]atrim=1.00:3.00" in filters
        # fades sit strictly inside the window: in at 0, out finishing at 2.00
        assert ",afade=t=out:st=1.990:d=0.010[vox1]" in filters

    def test_vocal_envelope_shrinks_for_very_short_windows(self):
        # a window shorter than two fade lengths must not get overlapping ramps
        filters = MockPlugger(
            [(10.0, 10.01)], duration=60.0, autoGenerateMode=True,
            segMapping=[(10.0, 10.01, 0.0, 0.01, 9.0, 10.0)],
            reverseMode=True, vocalsFileSpec="/tmp/combined_vocals.wav",
        ).filters()

        assert "areverse,afade=t=in:st=0:d=0.005,afade=t=out:st=0.005:d=0.005[vox1]" in filters

    def test_no_vocal_stem_falls_back_to_instrumental_only(self):
        # without a separated vocal stem (e.g. separation returned only one path)
        # the filter must stay valid rather than reference a missing input
        filters = self.reverse_filters(vocals="")

        assert "[1:a]atrim=1.00:3.00,asetpts=PTS-STARTPTS[seg1]" in filters
        assert "[2:a]" not in filters
        assert "areverse" not in filters

    def test_traditional_mode_ignores_reverse_mode(self):
        # reverse mode is an AI generation feature; a user-supplied instrumental
        # has no vocal stem to reverse
        filters = MockPlugger(
            [(10.0, 12.0)], duration=60.0, reverseMode=True,
            vocalsFileSpec="/tmp/combined_vocals.wav",
        ).filters()

        assert "[1:a]atrim=10.00:12.00,asetpts=PTS-STARTPTS[seg1]" in filters
        assert "[2:a]" not in filters
        assert "areverse" not in filters


